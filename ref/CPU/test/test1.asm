# ==================================================================
# 单周期CPU测试程序 (RISC-V RV32I 子集)
# 测试指令: ORI, ADD, SUB, SW, LW, BEQ
# 寄存器使用 ABI 命名 (zero, ra, sp, gp, tp, t0-t2, s0-s1, a0-a7)

# 本测试样例由Claude Code + Deepseek-v4-pro API生成，经作者审查
# ==================================================================

    # ===== 1: ORI 初始化 (零扩展) =====
    ori  t0, zero, 1          # t0  = 0x00000001
    ori  t1, zero, 2          # t1  = 0x00000002
    ori  a0, zero, 0x0100      # a0  = 0x00000100 (内存基址)

    # ===== 2: ADD / SUB =====
    add  t2, t0, t1           # t2  = 1+2 = 3
    sub  tp, t1, t0           # tp  = 2-1 = 1

    # ===== 3: SW / LW =====
    sw   t2, 0(a0)            # mem[0x100] = 3
    lw   s0, 0(a0)            # s0  = mem[0x100] = 3

    # ===== 4: 混合运算 =====
    add  s1, s0, t0           # s1  = 3+1 = 4
    sub  a1, s1, t1           # a1  = 4-2 = 2

    # ===== 5: 带偏移的 SW/LW =====
    sw   a1, 4(a0)            # mem[0x104] = 2
    lw   a3, 4(a0)            # a3  = mem[0x104] = 2

    # ===== 6: BEQ 条件成立 (零==零, 应跳转) =====
    ori  a4, zero, 0          # a4  = 0
    beq  zero, a4, skip1      # 0==0 → taken, 跳到 skip1
    ori  a5, zero, 0x0BD      # 被跳过 (不执行)

    # ===== 7: BEQ 条件不成立 (1≠2, 应顺序执行) =====
skip1:
    beq  t0, t1, dead         # 1≠2 → not taken
    ori  a5, zero, 0x0FF       # a5  = 0xFF (正常执行)

    # ===== 8: 最终计算 =====
    add  a6, a5, t0           # a6  = 0xFF+1 = 0x100
    sub  a7, a6, t1           # a7  = 0x100-2 = 0xFE
    sw   a7, 8(a0)            # mem[0x108] = 0xFE

    # ===== 9: 自循环停机 =====
end:
    beq  zero, zero, end      # 无条件自跳转

    # ===== 死代码 (不应到达) =====
dead:
    ori  a5, zero, 0x0DE    # 错误标记


